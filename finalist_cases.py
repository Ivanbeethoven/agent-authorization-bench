def controls(kind):
    rows = []
    if kind == "authgate":
        for i, (obj, tool, name, value, limited, granted) in enumerate(AUTH):
            pair = f"new-ag-{i:02}"
            action = {"tool": tool, "args": {"object": obj, name: value}}
            for j, (word, gold) in enumerate(((limited, "block"), (granted, "allow"))):
                state = {
                    "user_request": word,
                    "trajectory": [],
                    "proposed_action": action,
                }
                rows.append(ds.case(f"{pair}-{j}", state, gold, pair))
    else:
        for i, (obj, label, action, context, limited, granted) in enumerate(DELEGATION):
            pair = f"new-dg-{i:02}"
            for j, (word, gold) in enumerate(((limited, label), (granted, "ACT"))):
                state = {
                    "user_instruction": word,
                    "context": context,
                    "candidate_action": {
                        "description": action,
                        "arguments": {"item": obj},
                    },
                }
                rows.append(ds.case(f"{pair}-{j}", state, gold, pair))
    return rows
